interface Glyph { w: number; h: number; rows: string[] }

function parse(src: Record<string, string>): Map<string, Glyph> {
  const m = new Map<string, Glyph>();
  for (const k in src) {
    const rows = src[k].split(' ');
    m.set(k, { w: rows[0].length, h: rows.length, rows });
  }
  return m;
}

const FONT_MAIN = parse(G7);
const FONT_SMALL = parse(G5);

export type FontId = 'main' | 'small';

export interface TextOpts {
  color?: string;
  align?: 'left' | 'center' | 'right';
  scale?: number;
  font?: FontId;
  /** Цвет тени (1 px вниз-вправо). */
  shadow?: string | null;
  /** Цвет обводки по 4 сторонам. */
  outline?: string | null;
  /** Межбуквенный интервал. */
  spacing?: number;
}

function glyphOf(font: FontId, ch: string): Glyph | undefined {
  if (font === 'small') {
    const up = ch.toUpperCase();
    return FONT_SMALL.get(ch) ?? FONT_SMALL.get(up) ?? FONT_SMALL.get(ALIAS_SMALL[up] ?? '');
  }
  const up = ch.toUpperCase();
  return FONT_MAIN.get(up) ?? FONT_MAIN.get(ALIAS[up] ?? '');
}

const spaceW = (font: FontId) => (font === 'small' ? 2 : 3);
const lineH = (font: FontId) => (font === 'small' ? 6 : 9);

export function textWidth(s: string, o: TextOpts = {}): number {
  const font = o.font ?? 'main', sc = o.scale ?? 1, sp = o.spacing ?? 1;
  let w = 0;
  for (const ch of s) {
    if (ch === ' ') { w += spaceW(font) + sp; continue; }
    const g = glyphOf(font, ch);
    w += (g ? g.w : 3) + sp;
  }
  return Math.max(0, w - sp) * sc;
}

export const textHeight = (o: TextOpts = {}): number => lineH(o.font ?? 'main') * (o.scale ?? 1);

// Кеш отрисованных глифов: ключ font|char|color
const glyphCanvas = new Map<string, HTMLCanvasElement | null>();

function glyphImage(font: FontId, ch: string, color: string): HTMLCanvasElement | null {
  const key = font + '|' + ch + '|' + color;
  let c = glyphCanvas.get(key);
  if (c !== undefined) return c;
  const g = glyphOf(font, ch);
  if (!g) { glyphCanvas.set(key, null); return null; }
  c = document.createElement('canvas');
  c.width = g.w; c.height = g.h;
  const x = c.getContext('2d')!;
  x.fillStyle = color;
  for (let y = 0; y < g.h; y++) for (let i = 0; i < g.w; i++) if (g.rows[y][i] === '#') x.fillRect(i, y, 1, 1);
  glyphCanvas.set(key, c);
  return c;
}

function drawRaw(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, font: FontId, sc: number, sp: number) {
  let cx = x;
  for (const ch of s) {
    if (ch === ' ') { cx += (spaceW(font) + sp) * sc; continue; }
    const g = glyphOf(font, ch);
    if (!g) { cx += (3 + sp) * sc; continue; }
    const img = glyphImage(font, ch, color);
    if (img) ctx.drawImage(img, cx, y, g.w * sc, g.h * sc);
    cx += (g.w + sp) * sc;
  }
}

/** Рисует строку пиксельным шрифтом; возвращает ширину. */
export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, o: TextOpts = {}): number {
  const font = o.font ?? 'main', sc = o.scale ?? 1, sp = o.spacing ?? 1;
  const w = textWidth(s, o);
  if (o.align === 'center') x = Math.round(x - w / 2);
  else if (o.align === 'right') x = Math.round(x - w);
  x = Math.round(x); y = Math.round(y);
  if (o.outline) {
    for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) drawRaw(ctx, s, x + dx * sc, y + dy * sc, o.outline, font, sc, sp);
  } else if (o.shadow !== null) {
    drawRaw(ctx, s, x + sc, y + sc, o.shadow ?? '#07060b', font, sc, sp);
  }
  drawRaw(ctx, s, x, y, o.color ?? '#ebe5e6', font, sc, sp);
  return w;
}

/** Перенос строк по ширине в пикселях (с учётом явных \n). */
export function wrapText(s: string, maxW: number, o: TextOpts = {}): string[] {
  const out: string[] = [];
  for (const para of s.split('\n')) {
    let cur = '';
    for (const word of para.split(' ')) {
      const cand = cur ? cur + ' ' + word : word;
      if (cur && textWidth(cand, o) > maxW) { out.push(cur); cur = word; } else cur = cand;
    }
    out.push(cur);
  }
  return out;
}

export function drawWrapped(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, maxW: number, o: TextOpts = {}, gap = 1): number {
  const lines = wrapText(s, maxW, o);
  const lh = textHeight(o) + gap;
  lines.forEach((l, i) => drawText(ctx, l, x, y + i * lh, o));
  return lines.length * lh;
}
